type MissingInstallerError struct {
	ProfilePath string
}

func (e MissingInstallerError) Error() string {
	return "no supported iOS profile installer found in PATH"
}

type InstallerRunError struct {
	Display string
	Err     error
	Output  string
}

func (e InstallerRunError) Error() string {
	return fmt.Sprintf("%s failed: %v", e.Display, e.Err)
}

type Options struct {
	CertPath string
	OutPath  string
	Name     string
	Install  bool
}

func Build(options Options) ([]byte, error) {
	if strings.TrimSpace(options.CertPath) == "" {
		return nil, fmt.Errorf("missing Burp CA certificate path")
	}
	if strings.TrimSpace(options.Name) == "" {
		options.Name = "Burp Suite CA"
	}
	cert, err := os.ReadFile(options.CertPath)
	if err != nil {
		return nil, err
	}
	certDER := certBytes(cert)
	if len(certDER) == 0 {
		return nil, fmt.Errorf("certificate file is empty or invalid")
	}
	payloadUUID, err := uuid()
	if err != nil {
		return nil, err
	}
	profileUUID, err := uuid()
	if err != nil {
		return nil, err
	}
	now := time.Now().UTC().Format("20060102150405")
	return []byte(fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>PayloadContent</key>
  <array>
    <dict>
      <key>PayloadCertificateFileName</key>
      <string>%s.cer</string>
      <key>PayloadContent</key>
      <data>%s</data>
      <key>PayloadDescription</key>
      <string>Installs the Burp Suite CA certificate for authorized iOS traffic interception lab testing.</string>
      <key>PayloadDisplayName</key>
      <string>%s</string>
      <key>PayloadIdentifier</key>
      <string>com.waariss.jailbreakit.burp-ca.%s.cert</string>
      <key>PayloadType</key>
      <string>com.apple.security.root</string>
      <key>PayloadUUID</key>
      <string>%s</string>
      <key>PayloadVersion</key>
      <integer>1</integer>
    </dict>
  </array>
  <key>PayloadDescription</key>
  <string>Burp CA profile generated by jailbreakit for authorized iOS security testing only.</string>
  <key>PayloadDisplayName</key>
  <string>%s</string>
  <key>PayloadIdentifier</key>
  <string>com.waariss.jailbreakit.burp-ca.%s</string>
  <key>PayloadOrganization</key>
  <string>jailbreakit</string>
  <key>PayloadRemovalDisallowed</key>
  <false/>
  <key>PayloadType</key>
  <string>Configuration</string>
  <key>PayloadUUID</key>
  <string>%s</string>
  <key>PayloadVersion</key>
  <integer>1</integer>
</dict>
</plist>
`, html.EscapeString(options.Name), base64.StdEncoding.EncodeToString(certDER), html.EscapeString(options.Name), now, payloadUUID, html.EscapeString(options.Name), now, profileUUID)), nil
}

func Write(options Options) (string, error) {
	profile, err := Build(options)
	if err != nil {
		return "", err
	}
	out := strings.TrimSpace(options.OutPath)
	if out == "" {
		out = "burp-ca.mobileconfig"
	}
	if dir := filepath.Dir(out); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return "", err
		}
	}
	if err := os.WriteFile(out, profile, 0o644); err != nil {
		return "", err
	}
	return out, nil
}

func Install(profilePath string, stdout, stderr io.Writer) error {
	if strings.TrimSpace(profilePath) == "" {
		return fmt.Errorf("missing mobileconfig path")
	}
	command, ok := profileInstaller(profilePath)
	if !ok {
		return MissingInstallerError{ProfilePath: profilePath}
	}
	fmt.Fprintf(stdout, "[*] Installing profile with %s\n", command.display)
	cmd := exec.Command(command.path, command.args...)
	cmd.Stdin = os.Stdin
	var output bytes.Buffer
	cmd.Stdout = &output
	cmd.Stderr = &output
	err := cmd.Run()
	if output.Len() > 0 {
		if err == nil {
			_, _ = stdout.Write(output.Bytes())
		} else {
			fmt.Fprintln(stderr, firstUsefulLine(output.String()))
		}
	}
	if err != nil {
		return InstallerRunError{
			Display: command.display,
			Err:     err,
			Output:  output.String(),
		}
	}
	return nil
}

func IsMissingInstaller(err error) bool {
	var missing MissingInstallerError
	return errors.As(err, &missing)
}

func IsInstallerRunError(err error) bool {
	var runErr InstallerRunError
	return errors.As(err, &runErr)
}

