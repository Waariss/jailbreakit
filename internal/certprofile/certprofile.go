func certBytes(content []byte) []byte {
	block, _ := pem.Decode(content)
	if block != nil && block.Type == "CERTIFICATE" {
		return block.Bytes
	}
	return content
}

func firstUsefulLine(text string) string {
	lines := strings.Split(text, "\n")
	for _, line := range lines {
		line = strings.TrimSpace(line)
		if isUsefulErrorLine(line) {
			return line
		}
	}
	for _, line := range lines {
		line = strings.TrimSpace(line)
		if line == "" || strings.Contains(line, "Traceback") || strings.HasPrefix(line, "│") || strings.HasPrefix(line, "╭") || strings.HasPrefix(line, "╰") {
			continue
		}
		return line
	}
	return strings.TrimSpace(text)
}

func isUsefulErrorLine(line string) bool {
	if line == "" || strings.Contains(line, "Traceback") {
		return false
	}
	return strings.Contains(line, "Error:") || strings.Contains(line, "error:") || strings.Contains(line, "PermissionError:")
}

type installCommand struct {
	path    string
	args    []string
	display string
}

func profileInstaller(profilePath string) (installCommand, bool) {
	candidates := []struct {
		binary  string
		args    []string
		display string
	}{
		{
			binary:  "ideviceprofile",
			args:    []string{"install", profilePath},
			display: "ideviceprofile",
		},
		{
			binary:  "pymobiledevice3",
			args:    []string{"profile", "install", profilePath},
			display: "pymobiledevice3 profile install",
		},
	}
	if runtimeGOOS() == "darwin" {
		candidates = append(candidates, struct {
			binary  string
			args    []string
			display string
		}{
			binary:  "cfgutil",
			args:    []string{"install-profile", profilePath},
			display: "cfgutil install-profile",
		})
	}
	for _, candidate := range candidates {
		path, err := exec.LookPath(candidate.binary)
		if err == nil {
			return installCommand{
				path:    path,
				args:    candidate.args,
				display: candidate.display,
			}, true
		}
	}
	return installCommand{}, false
}

func uuid() (string, error) {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", err
	}
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	return fmt.Sprintf("%08x-%04x-%04x-%04x-%012x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16]), nil
}

var runtimeGOOS = func() string {
	return runtime.GOOS
}
